#!/usr/bin/env python3
"""Update the zynthian package of this repository to a release and send the PR to zynthian-packages.

usage: tools/package_pr.py [vX.Y.Z | --latest-build] [--no-pr] [--dry-run] [--yes]

  vX.Y.Z          release tag to publish (default: the newest vX.Y.Z tag of the GitHub repository)
  --latest-build  no release: the package installs the latest build (VERSION="" and no version in info.yml)
  --no-pr         only update package/ (VERSION in the package script, version in package/info.yml)
  --dry-run       update package/ and show what the PR would change in the catalog; send nothing
  --yes           don't ask before sending the PR

What it does:
  1. Checks the release: the tag exists on GitHub and, for plugins, matches the plugin version in the code and has
     the x86_64 and arm64 bundles built by the CI workflow.
  2. Updates package/: VERSION="vX.Y.Z" in package/<Package>.sh and version: "X.Y.Z" in package/info.yml.
  3. Sends a PR to zynthian-packages (needs the GitHub CLI `gh`, logged in): from your fork, copying package/ to
     Plugins/<Package>/ or Widgets/<Package>/. Nothing is sent if the catalog already has the same package.

Commit the changes of package/ to this repository too. Generated by the zynthian-lv2-plugin skill.
"""

import argparse
import glob
import os
import re
import shutil
import subprocess
import sys
import tempfile

CATALOG = "zynthian/zynthian-packages"
CATEGORIES = {"lv2_plugin": "Plugins", "lv2_widget": "Widgets"}


def fail(msg):
    print(f"ERROR: {msg}", file=sys.stderr)
    sys.exit(1)


def run(*cmd, cwd=None, check=True):
    res = subprocess.run(cmd, capture_output=True, text=True, cwd=cwd)
    if check and res.returncode != 0:
        fail(f"{' '.join(cmd)}: {(res.stderr or res.stdout).strip()}")
    return res.stdout.rstrip()


def version_key(tag):
    return [int(n) for n in re.findall(r"\d+", tag)]


def var(text, name):
    found = re.search(rf'^{name}="(.*)"$', text, re.M)
    return found.group(1) if found else None


def newest_tag(repo_url):
    tags = re.findall(r"refs/tags/(v\d+\.\d+\.\d+)$", run("git", "ls-remote", "--tags", "--refs", repo_url, "v*"), re.M)
    if not tags:
        fail("no vX.Y.Z tag in the GitHub repository: tag a release first (git tag vX.Y.Z && git push --tags)")
    return max(tags, key=version_key)


def check_release(root, tag, github, symbol):
    """The tag is on GitHub; plugins: it matches the plugin version and its release has the bundles."""
    if not run("git", "ls-remote", "--tags", "--refs", f"https://github.com/{github}.git", tag):
        fail(f"tag {tag} is not on GitHub ({github}): git push --tags")
    sources = glob.glob(os.path.join(root, "plugins", "*", "Plugin.cpp"))
    if not sources:
        return  # widget bundle: nothing else to check
    code = re.search(r"d_version\((\d+),\s*(\d+),\s*(\d+)\)", open(sources[0]).read())
    if code and tag != "v" + ".".join(code.groups()):
        fail(f"tag {tag} doesn't match the plugin version v{'.'.join(code.groups())} ({sources[0]}, getVersion)")
    if not shutil.which("gh"):
        print("WARNING: gh not found: the bundles of the release were not checked")
        return
    assets = run("gh", "release", "view", tag, "--repo", github, "--json", "assets", "-q", ".assets[].name").split()
    missing = [f"{symbol}-lv2-{arch}.tar.gz" for arch in ("x86_64", "arm64") if f"{symbol}-lv2-{arch}.tar.gz" not in assets]
    if missing:
        fail(f"the release {tag} lacks {', '.join(missing)}: wait for the CI build of the tag")


def set_release(script_path, info_path, tag):
    script = re.sub(r'^VERSION=".*"$', f'VERSION="{tag}"', open(script_path).read(), flags=re.M)
    open(script_path, "w").write(script)
    info = re.sub(r"^version:.*\n", "", open(info_path).read(), flags=re.M)
    if tag:
        info = re.sub(r"^(title:.*\n)", rf'\1version: "{tag[1:]}"\n', info, count=1, flags=re.M)
    open(info_path, "w").write(info)


def check_package(pkg, info_path):
    info = open(info_path).read()
    if "TODO" in info:
        fail(f"{info_path} still has TODO placeholders (description, size...)")
    icon = re.search(r'^icon:\s*"(.*)"', info, re.M)
    if not icon or not os.path.isfile(os.path.join(pkg, icon.group(1))):
        fail(f"{info_path}: the icon image is missing (a screenshot of the widget in package/Art)")


def send_pr(pkg, category, name, tag, github, dry_run, yes):
    with tempfile.TemporaryDirectory() as tmp:
        clone = os.path.join(tmp, "catalog")
        run("git", "clone", "-q", "--depth", "1", f"https://github.com/{CATALOG}.git", clone)
        dest = os.path.join(clone, category, name)
        is_new = not os.path.isdir(dest)
        shutil.rmtree(dest, ignore_errors=True)
        shutil.copytree(pkg, dest)
        changes = run("git", "status", "--porcelain", cwd=clone)
        if not changes:
            print(f"The catalog already has this {name} package: nothing to send.")
            return
        print(f"Changes in {CATALOG} ({category}/{name}):")
        print(changes)
        if dry_run:
            print("Dry run: nothing sent.")
            return
        if not shutil.which("gh"):
            fail("the GitHub CLI (gh) is needed to send the PR: https://cli.github.com")
        if not yes and input(f"Send the PR to {CATALOG}? [y/N] ").strip().lower() != "y":
            print("Not sent.")
            return
        me = run("gh", "api", "user", "-q", ".login")
        run("gh", "repo", "fork", CATALOG, "--clone=false")
        ssh = run("gh", "config", "get", "git_protocol", check=False) == "ssh"
        fork_url = f"git@github.com:{me}/zynthian-packages.git" if ssh else f"https://github.com/{me}/zynthian-packages.git"
        branch = f"{re.sub(r'[^a-z0-9]+', '-', name.lower()).strip('-')}-{tag or 'latest-build'}"
        what = f"{name} {tag}" if tag else f"{name} (latest build)"
        title = f"Add {what}" if is_new else f"Update {what}"
        run("git", "checkout", "-q", "-b", branch, cwd=clone)
        run("git", "add", "-A", cwd=clone)
        run("git", "commit", "-q", "-m", title, cwd=clone)
        run("git", "push", "-q", "--force", fork_url, branch, cwd=clone)
        body = (f"{'New package' if is_new else 'Update of the package'} **{name}** ({category}) from "
                f"https://github.com/{github}: " + (f"release {tag}." if tag else "installs the latest build.")
                + f"\n\nChanged files:\n```\n{changes}\n```\n\nSent with tools/package_pr.py")
        print(run("gh", "pr", "create", "--repo", CATALOG, "--head", f"{me}:{branch}", "--base", "main",
                  "--title", title, "--body", body))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("tag", nargs="?", help="release tag vX.Y.Z (default: the newest one)")
    ap.add_argument("--latest-build", action="store_true")
    ap.add_argument("--no-pr", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--yes", action="store_true")
    args = ap.parse_args()
    if args.tag and (args.latest_build or not re.match(r"^v\d+\.\d+\.\d+$", args.tag)):
        fail("give a vX.Y.Z tag, or --latest-build")

    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    pkg = os.path.join(root, "package")
    scripts = glob.glob(os.path.join(pkg, "*.sh"))
    info_path = os.path.join(pkg, "info.yml")
    if len(scripts) != 1 or not os.path.isfile(info_path):
        fail(f"{pkg}: expected info.yml and one <Package>.sh")
    script_path = scripts[0]
    script = open(script_path).read()
    github, ptype = var(script, "GITHUB"), var(script, "PACKAGE_TYPE")
    if not github or ptype not in CATEGORIES or var(script, "VERSION") is None:
        fail(f"{script_path}: needs the PACKAGE_TYPE, GITHUB and VERSION lines (zynthian-packages library)")
    name = os.path.basename(script_path)[:-3]

    tag = ""
    if not args.latest_build:
        tag = args.tag or newest_tag(f"https://github.com/{github}.git")
        check_release(root, tag, github, var(script, "SYMBOL"))
    set_release(script_path, info_path, tag)
    print(f"package/: VERSION=\"{tag}\", " + (f'version "{tag[1:]}"' if tag else "no version (latest build)"))
    if args.no_pr:
        return 0
    check_package(pkg, info_path)
    send_pr(pkg, CATEGORIES[ptype], name, tag, github, args.dry_run, args.yes)
    return 0


if __name__ == "__main__":
    sys.exit(main())
