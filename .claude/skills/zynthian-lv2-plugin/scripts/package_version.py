#!/usr/bin/env python3
"""Set the release a zynthian package installs (package/ of a plugin project or a widget repo).

usage: package_version.py <project_dir> [vX.Y.Z | --latest-build]

  vX.Y.Z          release tag to install (default: the newest v* tag in the GitHub repo). Sets VERSION="vX.Y.Z" in
                  package/<Package>.sh and version: "X.Y.Z" in package/info.yml: webconf offers an update when the
                  catalog's version is newer than the installed one.
  --latest-build  no release: VERSION="" (install the latest CI build / last commit) and no version in info.yml.

Plugins: the tag must match the plugin version in spec.json and its release must have the x86_64 and arm64 bundles
(built by the CI workflow). Widgets: the tag must exist.

The package changes: send a PR to zynthian-packages (SKILL.md, step 5).
"""

import glob
import json
import os
import re
import subprocess
import sys


def fail(msg):
    print(f"ERROR: {msg}", file=sys.stderr)
    sys.exit(1)


def run(*cmd, cwd=None):
    res = subprocess.run(cmd, capture_output=True, text=True, cwd=cwd)
    if res.returncode != 0:
        fail(f"{' '.join(cmd)}: {res.stderr.strip()}")
    return res.stdout


def version_key(tag):
    return [int(n) for n in re.findall(r"\d+", tag)]


def main():
    args = sys.argv[1:]
    if not args or args[0] in ("-h", "--help") or len(args) > 2:
        print(__doc__)
        return 1
    project = os.path.abspath(os.path.expanduser(args[0]))
    choice = args[1] if len(args) > 1 else None
    pkg = os.path.join(project, "package")
    scripts = glob.glob(os.path.join(pkg, "*.sh"))
    info_path = os.path.join(pkg, "info.yml")
    if len(scripts) != 1 or not os.path.isfile(info_path):
        fail(f"{pkg}: expected info.yml and one <Package>.sh")
    script_path = scripts[0]
    script = open(script_path).read()
    github = re.search(r'^GITHUB="(.+)"$', script, re.M)
    if not github or not re.search(r'^VERSION=".*"$', script, re.M):
        fail(f"{script_path}: no GITHUB / VERSION lines (generated by the skill?)")
    github = github.group(1)
    is_plugin = os.path.isfile(os.path.join(project, "spec.json"))

    if choice == "--latest-build":
        tag = ""
    else:
        if choice:
            tag = choice
        else:
            tags = run("git", "ls-remote", "--tags", "--refs", f"https://github.com/{github}.git", "v*").split()
            tags = [t.split("refs/tags/")[1] for t in tags if "refs/tags/" in t]
            if not tags:
                fail(f"no v* tag in {github}: tag a release first (git tag vX.Y.Z && git push --tags), "
                     "or use --latest-build")
            tag = max(tags, key=version_key)
        if not re.match(r"^v\d+\.\d+\.\d+$", tag):
            fail(f"'{tag}' is not a vX.Y.Z tag")
        remote_tags = run("git", "ls-remote", "--tags", "--refs", f"https://github.com/{github}.git", tag)
        if not remote_tags.strip():
            fail(f"tag {tag} is not in {github}: git push --tags")
        if is_plugin:
            spec_version = ".".join(str(v) for v in json.load(open(os.path.join(project, "spec.json")))["version"])
            if tag != f"v{spec_version}":
                fail(f"tag {tag} doesn't match the plugin version v{spec_version} (spec.json, Plugin.cpp d_version)")
            assets = run("gh", "release", "view", tag, "--repo", github, "--json", "assets",
                         "-q", ".assets[].name").split()
            sym = json.load(open(os.path.join(project, "spec.json")))["symbol"]
            missing = [f"{sym}-lv2-{a}.tar.gz" for a in ("x86_64", "arm64") if f"{sym}-lv2-{a}.tar.gz" not in assets]
            if missing:
                fail(f"release {tag} of {github} lacks {', '.join(missing)}: wait for the CI build of the tag")

    script = re.sub(r'^VERSION=".*"$', f'VERSION="{tag}"', script, flags=re.M)
    open(script_path, "w").write(script)
    info = open(info_path).read()
    info = re.sub(r"^version:.*\n", "", info, flags=re.M)
    if tag:
        info = re.sub(r"^(title:.*\n)", rf'\1version: "{tag[1:]}"\n', info, count=1, flags=re.M)
    open(info_path, "w").write(info)

    print(f"{os.path.basename(script_path)}: VERSION=\"{tag}\"; info.yml: "
          + (f'version "{tag[1:]}"' if tag else "no version (latest build)"))
    print("Next: commit package/ and send the PR to zynthian-packages.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
